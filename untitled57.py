import requests
import pandas as pd
import time

# הגדרת כותרת זיהוי חובה לפי כללי Open Food Facts
headers = {
    "User-Agent": "FoodGuard_Student_Project/1.0 (Contact: student@example.com)"
}

# שימוש ב-API החדש (v2) ושליפה ב-5 עמודים של 100 מוצרים (סה"כ 500) כדי למנוע עומס וחסימות
url = "https://world.openfoodfacts.org/api/v2/search"
all_products = []

print("מושך 500 מוצרים מ-Open Food Facts (API v2)...")

for page in range(1, 6):
    params = {
        "countries_tags": "en:israel",
        "page_size": 100,
        "page": page,
        "fields": "code,product_name,brands,ingredients_text,ingredients_text_he,allergens_tags"
    }
    response = requests.get(url, params=params, headers=headers, timeout=20)

    if response.status_code == 200:
        products = response.json().get("products", [])
        all_products.extend(products)
        print(f"עמוד {page}/5 הושלם ({len(products)} מוצרים)")
    else:
        print(f"שגיאה בעמוד {page}: קוד {response.status_code}")

    time.sleep(1)  # המתנה קצרה בין בקשות כדי לכבד את השרת

df = pd.DataFrame(all_products)
print(f"\nנשלפו בהצלחה {len(df)} מוצרים סה\"כ!\n")

# ניתוח איכות נתונים ראשוני
has_ingredients_any = df['ingredients_text'].notna() & (df['ingredients_text'].astype(str).str.strip() != "") & (df['ingredients_text'].astype(str) != "nan")
has_ingredients_he = df['ingredients_text_he'].notna() & (df['ingredients_text_he'].astype(str).str.strip() != "") & (df['ingredients_text_he'].astype(str) != "nan")
has_allergen_tags = df['allergens_tags'].apply(lambda x: isinstance(x, list) and len(x) > 0)

# זיהוי סתירות / מידע חלקי: יש תגית אלרגן אך אין רשימת רכיבים
contradictions = df[has_allergen_tags & (~has_ingredients_any)]

print("--- סיכום איכות הנתונים (פיילוט ישראל) ---")
print(f"מוצרים עם טקסט רכיבים כלשהו: {has_ingredients_any.sum()} ({has_ingredients_any.mean()*100:.1f}%)")
print(f"מוצרים עם טקסט רכיבים בעברית: {has_ingredients_he.sum()} ({has_ingredients_he.mean()*100:.1f}%)")
print(f"מוצרים עם תגיות אלרגנים מובנות: {has_allergen_tags.sum()} ({has_allergen_tags.mean()*100:.1f}%)")
print(f"מוצרים עם מידע חלקי/סתירה (יש תגית אלרגן אך אין רכיבים): {len(contradictions)}")

# שמירת הנתונים לקובץ CSV
df.to_csv("off_israel_pilot_500.csv", index=False, encoding="utf-8-sig")
print("\nהקובץ off_israel_pilot_500.csv נשמר בהצלחה!")